use std::{env, fs, path::PathBuf};

// Tauri requires a PNG while expanding `generate_context!`. Keep the scaffold's
// placeholder out of the repository (some review systems reject binary diffs)
// and reproduce it before Tauri reads the application configuration.
const PLACEHOLDER_ICON: &[u8] = &[
    0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a, 0x00, 0x00, 0x00, 0x0d, 0x49, 0x48, 0x44, 0x52,
    0x00, 0x00, 0x00, 0x20, 0x00, 0x00, 0x00, 0x20, 0x08, 0x06, 0x00, 0x00, 0x00, 0x73, 0x7a, 0x7a,
    0xf4, 0x00, 0x00, 0x00, 0x2f, 0x49, 0x44, 0x41, 0x54, 0x78, 0x9c, 0xed, 0xce, 0x21, 0x01, 0x00,
    0x00, 0x08, 0x03, 0x30, 0x0a, 0x11, 0x89, 0x6e, 0x34, 0x85, 0x18, 0x37, 0x13, 0xf3, 0xab, 0x9e,
    0xbd, 0xa4, 0x12, 0x10, 0x10, 0x10, 0x10, 0x10, 0x10, 0x10, 0x10, 0x10, 0x10, 0x10, 0x10, 0x10,
    0x10, 0x48, 0x07, 0x1e, 0xf2, 0xf8, 0xa4, 0x79, 0x5b, 0x16, 0xd8, 0xc6, 0x00, 0x00, 0x00, 0x00,
    0x49, 0x45, 0x4e, 0x44, 0xae, 0x42, 0x60, 0x82,
];

fn main() {
    let icon_directory =
        PathBuf::from(env::var_os("CARGO_MANIFEST_DIR").expect("missing crate root")).join("icons");
    let png_path = icon_directory.join("icon.png");
    if !png_path.exists() {
        fs::create_dir_all(&icon_directory).expect("failed to create the Tauri icon directory");
        fs::write(png_path, PLACEHOLDER_ICON).expect("failed to generate the PNG placeholder icon");
    }

    let ico_path = icon_directory.join("icon.ico");
    if !ico_path.exists() {
        let mut ico = vec![
            0, 0, // reserved
            1, 0, // ICO image type
            1, 0, // one image
            32, 32, // width and height
            0,  // no color palette
            0,  // reserved
            1, 0, // color planes
            32, 0, // bits per pixel
        ];
        ico.extend_from_slice(&(PLACEHOLDER_ICON.len() as u32).to_le_bytes());
        ico.extend_from_slice(&22_u32.to_le_bytes());
        ico.extend_from_slice(PLACEHOLDER_ICON);
        fs::write(ico_path, ico).expect("failed to generate the ICO placeholder icon");
    }
    tauri_build::build()
}
