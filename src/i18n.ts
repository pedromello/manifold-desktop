export const supportedLanguages = ['pt-BR', 'en-US'] as const;
export type SupportedLanguage = (typeof supportedLanguages)[number];

function initialLanguage(): SupportedLanguage {
  const saved = window.localStorage.getItem('manifold.language');
  if (saved === 'pt-BR' || saved === 'en-US') return saved;
  return navigator.language.toLowerCase().startsWith('pt') ? 'pt-BR' : 'en-US';
}

